"""把第二轮实验结果写成LaTeX表格与数值宏，不改五份主结果工作簿。"""
import json
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1];R=ROOT/'results';T=ROOT/'tables'
S=json.loads((R/'summary.json').read_text(encoding='utf-8'))['cases']
D=json.loads((R/'refinements.json').read_text(encoding='utf-8'));C=D['cases'];V=D['validation']
def number(x):return f'{float(x):.2f}'
def table(name,caption,headers,rows):
    text='\\begin{table}[H]\\centering\\small\n\\caption{'+caption+'}\\label{tab:'+name+'}\n'
    text+='\\begin{tabular}{l'+'r'*(len(headers)-1)+'}\\toprule\n'
    text+=' & '.join(headers)+r' \\\midrule'+'\n'
    text+='\n'.join(' & '.join(map(str,row))+r' \\' for row in rows)
    text+='\n\\bottomrule\\end{tabular}\\end{table}\n'
    (T/(name+'.tex')).write_text(text,encoding='utf-8')
rows=[]
for base,prefix in [('q2','重复价'),('q4_2','波动价')]:
    for key,desc in [(base,'可实施日前'),(base+'_daily_oracle','当日先知'),(base+'_full_oracle','全期先知')]:
        c=S[key] if key in S else C[key]
        rows.append([prefix+'：'+desc,number(c['total_cost']),number(c['emergency_kwh']),number(c['start_energy']),number(c['end_energy'])])
table('information_benchmark','信息设定对照；费用为元，电量为kWh',
      ['信息与策略','总费用','紧急电量','期初SOC','期末SOC'],rows)
rows=[]
for g in ('0.0','0.5','1.0','1.5'):
    rows.append([g,number(V['q2_terminal']['scores'][g]['adjusted_cost']),number(V['q4_2_terminal']['scores'][g]['adjusted_cost'])])
table('terminal_validation','仅用1月15--31日选择终端价值；数值为库存修正费用/元',
      [r'$\gamma$','重复电价','波动电价'],rows)
rows=[]
for base,label in [('q2','重复电价'),('q4_2','波动电价')]:
    for key,desc in [(base,'原模型'),(base+'_terminal','终端价值')]:
        c=S[key] if key in S else C[key]
        rows.append([label+'：'+desc,number(c.get('gamma',0)),number(c['total_cost']),number(c['emergency_kwh']),number(c['end_energy'])])
table('terminal_results','终端价值的报告期检验；不将虚拟库存收益计入现金费用',
      ['方案',r'$\gamma$','总费用/元','紧急电量/kWh','期末SOC/kWh'],rows)
names={'last':'前一日','mean3':'3日均值','mean7':'7日均值','ewma14':'指数加权','weekday':'同星期'}
rows=[]
for method in names:
    a=V['q2_economic']['scores'][method];b=V['q4_2_economic']['scores'][method]
    rows.append([names[method],number(a['mae']),number(a['rmse']),number(a['adjusted_cost']),number(b['adjusted_cost'])])
table('economic_validation','光伏候选的1月顺序验证；费用均已按统一价格修正期末库存',
      ['候选方法','MAE/kW','RMSE/kW','重复价费用/元','波动价费用/元'],rows)
rows=[]
for base,label in [('q2','重复价'),('q4_2','波动价')]:
    for suffix,desc in [('_mae_control','MAE选型'),('_economic','费用选型')]:
        c=C[base+suffix]
        rows.append([label+'：'+desc,names[c['pv_method']],number(c['total_cost']),number(c['emergency_kwh'])])
table('economic_results','相同候选历史回放下的预测选型对照（2--12月）',
      ['选择规则','光伏方法','总费用/元','紧急电量/kWh'],rows)
rows=[]
for base,label in [('q3','重复价'),('q4_3','波动价')]:
    for key,desc in [(base,'直接滚动'),(base+'_gate','经济门控')]:
        c=S[key] if key in S else C[key]
        rows.append([label+'：'+desc,number(c['total_cost']),number(c['emergency_kwh']),str(c.get('accepted',1002)),str(c.get('rejected',0))])
table('gate_results','门控与直接滚动的同信息比较；次数为日内候选采纳/保留次数',
      ['方案','总费用/元','紧急电量/kWh','采纳','保留'],rows)
derived={}
for base in ('q2','q4_2'):
    derived[base+'oracle_gap']=S[base]['total_cost']-C[base+'_full_oracle']['total_cost']
    derived[base+'terminal_saving']=S[base]['total_cost']-C[base+'_terminal']['total_cost']
    derived[base+'economic_saving']=C[base+'_mae_control']['total_cost']-C[base+'_economic']['total_cost']
    derived[base+'economic_increase']=-derived[base+'economic_saving']
for base in ('q3','q4_3'):
    derived[base+'gate_saving']=S[base]['total_cost']-C[base+'_gate']['total_cost']
    derived[base+'gate_percent']=100*derived[base+'gate_saving']/S[base]['total_cost']
    ds=D['gate_decisions'][base+'_gate']
    derived[base+'gate_negative']=sum(x['expected_saving'] < -1e-6 for x in ds)
    derived[base+'gate_ties']=sum(abs(x['expected_saving'])<=1e-6 for x in ds)
macros=['% Generated by refinement_evidence.py; no handwritten result values.']
for group,values in dict(C,extra=derived).items():
    for field,value in values.items():
        if isinstance(value,(int,float)):
            macros.append('\\expandafter\\def\\csname result'+group+field+'\\endcsname{'+(str(value) if isinstance(value,int) else number(value))+'}')
(T/'refinement_metrics.tex').write_text('\n'.join(macros)+'\n',encoding='utf-8')
(R/'refinement_metrics.json').write_text(json.dumps(derived,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(derived,ensure_ascii=False,indent=2))
